import type { GenerationCaseResult, GenerationRunResult, GenerationTrackResult } from './types.ts'
import { parse } from 'csv-parse/sync'
import { aggregateGenerationRunsByCase } from './results.ts'
import { GENERATION_CASE_IDS, GENERATION_TRACK_IDS } from './types.ts'

/** Reads measured fields from either the historical or current runner's CSV. */
export function parseGenerationRuns(csv: string): GenerationRunResult[] {
  const rows = parse(csv, { columns: true, skip_empty_lines: true }) as Record<string, string>[]
  if (rows.length === 0)
    throw new Error('Generation CSV contains no runs')
  return rows.map((row) => {
    const run = numeric(row.run, 'run', 1)
    if (!row.model || !Number.isInteger(run))
      throw new Error('Each run must have a model and a positive integer run number')
    // Historical batches restarted run numbering; each CSV row is a measurement.
    const cases = {} as GenerationRunResult['cases']
    for (const caseId of GENERATION_CASE_IDS) {
      const result = {} as GenerationCaseResult
      for (const track of GENERATION_TRACK_IDS) {
        const suffix = track === 'json-object' ? 'json' : track === 'json-plain' ? 'json_plain' : 'toon'
        const prefix = `${caseId}_${suffix}`
        const measured: GenerationTrackResult = {
          oneShotOk: boolean(row[`${prefix}_one_shot`], `${prefix}_one_shot`),
          finalOk: boolean(row[`${prefix}_final`], `${prefix}_final`),
          attemptsUsed: numeric(row[`${prefix}_attempts`], `${prefix}_attempts`, 1),
          inputTokens: numeric(row[`${prefix}_prompt_tokens`], `${prefix}_prompt_tokens`),
          outputTokens: numeric(row[`${prefix}_completion_tokens`], `${prefix}_completion_tokens`),
        }
        if (!Number.isInteger(measured.attemptsUsed) || measured.attemptsUsed > 3)
          throw new Error(`Invalid attempt count: ${prefix}`)
        if (measured.oneShotOk && (!measured.finalOk || measured.attemptsUsed !== 1))
          throw new Error(`Inconsistent one-shot result: ${prefix}`)
        result[track] = measured
      }
      cases[caseId] = result
    }
    return { model: row.model, run, cases }
  })
}

/** Produces the same report from saved runs without making model requests. */
export function renderGenerationReport(results: GenerationRunResult[], historical = false): string {
  const models = new Set(results.map(result => result.model))
  const counts = [...models].map(model => results.filter(result => result.model === model).length)
  const runCount = Math.min(...counts) === Math.max(...counts)
    ? String(counts[0])
    : `${Math.min(...counts)}–${Math.max(...counts)}`
  const lines = [
    historical ? '### Historical Generation Baseline' : '### Structured Generation Results',
    '',
    historical
      ? 'These are the original Python benchmark results, preserved for reference. They are not a rerun with the current TypeScript harness or TOON v4. The historical TOON prompts omitted schema field information, so these scores are not comparable to the corrected harness.'
      : 'Generated by the TypeScript harness using the local TOON implementation. See the adjacent run metadata for model IDs, settings, and source fingerprints.',
    '',
    `${models.size} models; ${results.length} model-runs; ${runCount} runs per model; four cases and three formats per run.`,
    '',
    'JSON-object means JSON object mode, not schema-constrained decoding. 1-S is first-attempt accuracy; Fin includes up to two repairs; Tok is mean prompt plus completion tokens across all attempts for a case.',
    '',
    '| Case | JSON 1-S | JSON Fin | JSON Tok | JSON-object 1-S | JSON-object Fin | JSON-object Tok | TOON 1-S | TOON Fin | TOON Tok |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
  ]
  for (const row of aggregateGenerationRunsByCase(results)) {
    const cells = [String(row.case)]
    for (const prefix of ['J', 'JSO', 'T']) {
      cells.push(`${(Number(row[`${prefix}1S`]) * 100).toFixed(1)}%`)
      cells.push(`${(Number(row[`${prefix}F`]) * 100).toFixed(1)}%`)
      cells.push(Math.round(Number(row[`${prefix}T`])).toLocaleString('en-US'))
    }
    lines.push(`| ${cells.join(' | ')} |`)
  }
  lines.push('', 'The users, order, and invoice cases cover tabular or mixed structures; company covers nested arrays. Scores are specific to these prompts and model versions, not a general ranking of formats.', '')
  if (historical) {
    lines.push('Historical run numbers restart within the DeepSeek-R1 batches. All 210 distinct measurement rows are retained; model/run is not a unique key. The archived CSVs contain per-run metrics, not raw model responses or immutable provider version metadata.', '')
    lines.push('Regenerate this table locally with `pnpm -C benchmarks report:generation --historical`. The source is `benchmarks/results/generation/eval-runs.csv`; no API key is required.', '')
  }
  return lines.join('\n')
}

function numeric(input: string | undefined, field: string, minimum = 0): number {
  const value = Number(input)
  if (input === undefined || input.trim() === '' || !Number.isFinite(value) || value < minimum)
    throw new Error(`Invalid numeric field: ${field}`)
  return value
}

function boolean(input: string | undefined, field: string): boolean {
  if (input === 'True' || input === 'true')
    return true
  if (input === 'False' || input === 'false')
    return false
  throw new Error(`Invalid boolean field: ${field}`)
}
